#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	char	*d;
	size_t	max_copy;
	size_t	dst_len;
	size_t	src_len;

	if (size == 0)
		return (ft_strlen(src));
	dst_len = ft_strlen(dst);
	src_len = ft_strlen(src);
	if (size <= dst_len)
	{
		return (size + src_len);
	}
	d = dst + dst_len;
	max_copy = size - dst_len - 1;
	while (max_copy-- && *src)
	{
		*d++ = *src++;
	}
	*d = '\0';
	return (dst_len + src_len);
}
